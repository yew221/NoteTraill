import type { RetrospectiveDraft } from './retrospective.js';
import type { Experiences } from './experiences.js';
import type { ModelConfig } from './model.js';
import type { Id } from './contracts.js';
import type { AnswerDraft } from './answer.js';
import type { ModelTotals } from './model-run.js';
import type { ErrorCode } from './api.js';
import type { ToolResult, Scope } from './tools.js';
import type { ReviewContext } from './watch.js';
import type { ResumeContext, ResumeDraft, ResumeCoverage } from './continuation.js';

export const PROJECT_PROTOCOL_VERSION = 1;
export const WORKER_REQUEST_BYTES = 256 * 1024;
export type WorkerStart = { projectProtocolVersion: 1; type: 'RunStart'; runId: Id<'run'>; generation: number;
  sessionId: Id<'session'>; segmentId: Id<'segment'>; deadline: number; question: string;
  modelConfig: ModelConfig; preferences: string[]; thinking: 'off' | 'low'; scope: Scope;
  sourceHints: Array<{ sourceId: string; relativePath: string; state: string }>;
  context: { resumeFile: string | null; priorQuestions: string[]; priorTools: { id: string; result: ToolResult }[]; notice: string | null;
    review?: ReviewContext;
    conversation?:ResumeContext;
    experienceComparison?:true;
    answerReference?: { answerId: string; createdAt: string; blocks: ReviewContext['previous']; checks?: ReviewContext['previousChecks']; resume?:ResumeDraft; resumeCoverage?:ResumeCoverage; experiences?:Experiences; retrospective?:RetrospectiveDraft };
    attachments?: Array<{ sourceId: string; name: string; relativePath: string; state: string } | { state: 'unavailable' }> } };
export type WorkerRpc = { projectProtocolVersion: 1; type: 'Request'; runId: Id<'run'>; generation: number;
  id: number; operation: 'model' | 'verify' | 'tool' | 'results' | 'validate' | 'candidate'; data: unknown };
export type WorkerReply = { projectProtocolVersion: 1; type: 'Reply'; runId: Id<'run'>; generation: number;
  id: number; ok: boolean; data?: unknown; errorCode?: ErrorCode };
export type WorkerCandidate = { draft: AnswerDraft; model: string; sessionFile: string; entryId: string; userEntryId: string;
  usage: ModelTotals & { toolCalls: number; readBytes: number }; workerPid: number };
